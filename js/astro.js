// Эфемериды Солнца и Луны по низкоточным рядам (Meeus, «Astronomical Algorithms»): Луна ≈ 0,02°, Солнце ≈ 0,01°.
// Все направления «звёздные» — в системе J2000 (как каталог звёзд); Солнце для горизонта — на эпоху даты.
const Astro = (() => {
  const D2R = Math.PI / 180;
  const mod = (v, m) => ((v % m) + m) % m;
  const EPS2000 = 23.4392911 * D2R;

  const jdOf = ms => ms / 86400000 + 2440587.5;
  const yearsSince2000 = jd => (jd - 2451545.0) / 365.25;

  // экваториальные координаты из эклиптических J2000
  function eclToEq(lon, lat) {
    const sl = Math.sin(lon), cl = Math.cos(lon), sb = Math.sin(lat), cb = Math.cos(lat), se = Math.sin(EPS2000), ce = Math.cos(EPS2000);
    return { ra: mod(Math.atan2(sl * cb * ce - sb * se, cl * cb), 2 * Math.PI), dec: Math.asin(sb * ce + cb * se * sl) };
  }
  const eclPrecession = jd => 1.396971 * D2R * (jd - 2451545.0) / 36525;     // сдвиг долготы за время от J2000

  // ---------- Солнце ----------
  function sun(jd) {
    const T = (jd - 2451545.0) / 36525;
    const L0 = mod(280.46646 + 36000.76983 * T + 0.0003032 * T * T, 360);
    const M = mod(357.52911 + 35999.05029 * T - 0.0001537 * T * T, 360) * D2R;
    const C = (1.914602 - 0.004817 * T - 0.000014 * T * T) * Math.sin(M) + (0.019993 - 0.000101 * T) * Math.sin(2 * M) + 0.000289 * Math.sin(3 * M);
    const trueLon = (L0 + C) * D2R;
    const omega = (125.04 - 1934.136 * T) * D2R;
    const appLon = trueLon - (0.00569 + 0.00478 * Math.sin(omega)) * D2R;      // кажущаяся долгота эпохи даты
    const eps = (23.4392911 - 0.0130042 * T + 0.00256 * Math.cos(omega)) * D2R;
    const raDate = mod(Math.atan2(Math.cos(eps) * Math.sin(appLon), Math.cos(appLon)), 2 * Math.PI);
    const decDate = Math.asin(Math.sin(eps) * Math.sin(appLon));
    // J2000: убираем прецессию из долготы, широта Солнца ≈ 0
    const j = eclToEq(appLon - eclPrecession(jd), 0);
    const E = mod(L0 - 0.0057183 - raDate / D2R + 180, 360) - 180;              // уравнение времени, градусов
    return { lon: appLon, raDate, decDate, ra: j.ra, dec: j.dec, eotMin: E * 4 };
  }

  // ---------- Луна ----------
  // D, M, M', F: множители аргументов; l — Σl (1e-6°), r — Σr (1e-3 км); таблица 47.A
  const LR = [
    [0, 0, 1, 0, 6288774, -20905355], [2, 0, -1, 0, 1274027, -3699111], [2, 0, 0, 0, 658314, -2955968], [0, 0, 2, 0, 213618, -569925],
    [0, 1, 0, 0, -185116, 48888], [0, 0, 0, 2, -114332, -3149], [2, 0, -2, 0, 58793, 246158], [2, -1, -1, 0, 57066, -152138],
    [2, 0, 1, 0, 53322, -170733], [2, -1, 0, 0, 45758, -204586], [0, 1, -1, 0, -40923, -129620], [1, 0, 0, 0, -34720, 108743],
    [0, 1, 1, 0, -30383, 104755], [2, 0, 0, -2, 15327, 10321], [0, 0, 1, 2, -12528, 0], [0, 0, 1, -2, 10980, 79661],
    [4, 0, -1, 0, 10675, -34782], [0, 0, 3, 0, 10034, -23210], [4, 0, -2, 0, 8548, -21636], [2, 1, -1, 0, -7888, 24208],
    [2, 1, 0, 0, -6766, 30824], [1, 0, -1, 0, -5163, -8379], [1, 1, 0, 0, 4987, -16675], [2, -1, 1, 0, 4036, -12831],
    [2, 0, 2, 0, 3994, -10445], [4, 0, 0, 0, 3861, -11650], [2, 0, -3, 0, 3665, 14403], [0, 1, -2, 0, -2689, -7003],
    [2, 0, -1, 2, -2602, 0], [2, -1, -2, 0, 2390, 10056], [1, 0, 1, 0, -2348, 6322], [2, -2, 0, 0, 2236, -9884],
    [0, 1, 2, 0, -2120, 5751], [0, 2, 0, 0, -2069, 0], [2, -2, -1, 0, 2048, -4950], [2, 0, 1, -2, -1773, 4130],
    [2, 0, 0, 2, -1595, 0], [4, -1, -1, 0, 1215, -3958], [0, 0, 2, 2, -1110, 0], [3, 0, -1, 0, -892, 3258],
    [2, 1, 1, 0, -810, 2616], [4, -1, -2, 0, 759, -1897], [0, 2, -1, 0, -713, -2117], [2, 2, -1, 0, -700, 2354],
    [2, 1, -2, 0, 691, 0], [2, -1, 0, -2, 596, 0], [4, 0, 1, 0, 549, -1423], [0, 0, 4, 0, 537, -1117],
    [4, -1, 0, 0, 520, -1571], [1, 0, -2, 0, -487, -1739], [2, 1, 0, -2, -399, 0], [0, 0, 2, -2, -381, -4421],
    [1, 1, 1, 0, 351, 0], [3, 0, -2, 0, -340, 0], [4, 0, -3, 0, 330, 0], [2, -1, 2, 0, 327, 0],
    [0, 2, 1, 0, -323, 1165], [1, 1, -1, 0, 299, 0], [2, 0, 3, 0, 294, 0], [2, 0, -1, -2, 0, 8752],
  ];
  // таблица 47.B: широта
  const B = [
    [0, 0, 0, 1, 5128122], [0, 0, 1, 1, 280602], [0, 0, 1, -1, 277693], [2, 0, 0, -1, 173237], [2, 0, -1, 1, 55413], [2, 0, -1, -1, 46271],
    [2, 0, 0, 1, 32573], [0, 0, 2, 1, 17198], [2, 0, 1, -1, 9266], [0, 0, 2, -1, 8822], [2, -1, 0, -1, 8216], [2, 0, -2, -1, 4324],
    [2, 0, 1, 1, 4200], [2, 1, 0, -1, -3359], [2, -1, -1, 1, 2463], [2, -1, 0, 1, 2211], [2, -1, -1, -1, 2065], [0, 1, -1, -1, -1870],
    [4, 0, -1, -1, 1828], [0, 1, 0, 1, -1794], [0, 0, 0, 3, -1749], [0, 1, -1, 1, -1565], [1, 0, 0, 1, -1491], [0, 1, 1, 1, -1475],
    [0, 1, 1, -1, -1410], [0, 1, 0, -1, -1344], [1, 0, 0, -1, -1335], [0, 0, 3, 1, 1107], [4, 0, 0, -1, 1021], [4, 0, -1, 1, 833],
  ];
  function moon(jd) {
    const T = (jd - 2451545.0) / 36525;
    const Lp = mod(218.3164477 + 481267.88123421 * T - 0.0015786 * T * T, 360);
    const Dd = mod(297.8501921 + 445267.1114034 * T - 0.0018819 * T * T, 360) * D2R;
    const M = mod(357.5291092 + 35999.0502909 * T - 0.0001536 * T * T, 360) * D2R;
    const Mp = mod(134.9633964 + 477198.8675055 * T + 0.0087414 * T * T, 360) * D2R;
    const F = mod(93.2720950 + 483202.0175233 * T - 0.0036539 * T * T, 360) * D2R;
    const A1 = mod(119.75 + 131.849 * T, 360) * D2R, A2 = mod(53.09 + 479264.290 * T, 360) * D2R, A3 = mod(313.45 + 481266.484 * T, 360) * D2R;
    const E = 1 - 0.002516 * T - 0.0000074 * T * T;
    const ef = m => (m === 0 ? 1 : Math.abs(m) === 1 ? E : E * E);
    let sl = 0, sr = 0, sb = 0;
    for (const [d, m, mp, f, l, r] of LR) {
      const arg = d * Dd + m * M + mp * Mp + f * F, k = ef(m);
      sl += l * k * Math.sin(arg); sr += r * k * Math.cos(arg);
    }
    for (const [d, m, mp, f, b] of B) sb += b * ef(m) * Math.sin(d * Dd + m * M + mp * Mp + f * F);
    const Lr = Lp * D2R;
    sl += 3958 * Math.sin(A1) + 1962 * Math.sin(Lr - F) + 318 * Math.sin(A2);
    sb += -2235 * Math.sin(Lr) + 382 * Math.sin(A3) + 175 * Math.sin(A1 - F) + 175 * Math.sin(A1 + F) + 127 * Math.sin(Lr - Mp) - 115 * Math.sin(Lr + Mp);
    const lon = (Lp + sl / 1e6) * D2R, lat = (sb / 1e6) * D2R, dist = 385000.56 + sr / 1000;     // км
    const j = eclToEq(lon - eclPrecession(jd), lat);
    return { lon: mod(lon, 2 * Math.PI), lat, dist, ra: j.ra, dec: j.dec };
  }
  const unit = (ra, dec) => [Math.cos(dec) * Math.cos(ra), Math.cos(dec) * Math.sin(ra), Math.sin(dec)];

  // фаза: освещённая доля, «растёт ли», угловой радиус диска
  function moonPhase(jd) {
    const s = sun(jd), m = moon(jd);
    const a = unit(s.ra, s.dec), b = unit(m.ra, m.dec);
    const psi = Math.acos(Math.max(-1, Math.min(1, a[0] * b[0] + a[1] * b[1] + a[2] * b[2])));   // элонгация
    const el = mod(m.lon - s.lon + Math.PI, 2 * Math.PI) - Math.PI;
    return { illum: (1 - Math.cos(psi)) / 2, waxing: el > 0, elongation: psi, angRadius: Math.asin(1737.4 / m.dist) };
  }

  // Гринвичское звёздное время (градусы, эпоха даты)
  const gmstDeg = jd => mod(280.46061837 + 360.98564736629 * (jd - 2451545.0), 360);

  // всё, что нужно приложению для момента ms
  function solar(ms) {
    const jd = jdOf(ms), s = sun(jd), g = gmstDeg(jd) * D2R;
    const shift = 0.012812 * D2R * yearsSince2000(jd);        // сдвиг точки равноденствия по экватору от J2000
    return {
      dec: s.decDate,
      Hg: mod(g - s.raDate + Math.PI, 2 * Math.PI) - Math.PI,  // часовой угол Солнца на Гринвиче
      raSun: s.raDate - shift,                                 // H + raSun = звёздное время в системе J2000 (для каталога)
      eot: s.eotMin,
      jd,
    };
  }
  // экваториальный единичный вектор J2000 по эклиптическим J2000 координатам
  const eclVec = (lon, lat) => { const e = eclToEq(lon, lat); return unit(e.ra, e.dec); };
  // долгота восходящего узла орбиты Луны (J2000) и наклонение орбиты к эклиптике
  const moonNode = jd => { const T = (jd - 2451545.0) / 36525; return (125.0445479 - 1934.1362891 * T) * D2R - eclPrecession(jd); };
  const MOON_INCL = 5.1453964 * D2R;
  return { solar, sun, moon, moonPhase, jdOf, gmstDeg, unit, eclVec, moonNode, MOON_INCL };
})();
